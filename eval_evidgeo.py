def load_clip(model_id: str, device: str):
    """Load CLIP with eager attention (required for attention-rollout)."""
    torch.cuda.empty_cache()
    model = CLIPModel.from_pretrained(
        model_id, attn_implementation="eager"
    ).to(device).eval()

    for sub_cfg in [model.config,
                    model.config.vision_config,
                    model.config.text_config]:
        sub_cfg._attn_implementation         = "eager"
        sub_cfg._attn_implementation_autoset = False

    for m in model.vision_model.modules():
        if hasattr(m, "config"):
            m.config._attn_implementation = "eager"

    processor = CLIPProcessor.from_pretrained(model_id)
    return model, processor


def patch_clip_attention(model):
    """
    Restore output_attentions support stripped in transformers v5.
    Patches CLIPEncoderLayer, CLIPEncoder, and CLIPVisionTransformer
    so that attention weights flow through to the rollout computation.
    """
    # Layer-level patch
    def _encoder_layer_forward(self, hidden_states, attention_mask=None, **kwargs):
        residual      = hidden_states
        hidden_states = self.layer_norm1(hidden_states)
        hidden_states, attn_weights = self.self_attn(
            hidden_states=hidden_states,
            attention_mask=attention_mask,
            **kwargs,
        )
        hidden_states = residual + hidden_states
        residual      = hidden_states
        hidden_states = self.layer_norm2(hidden_states)
        hidden_states = self.mlp(hidden_states)
        hidden_states = residual + hidden_states
        return hidden_states, attn_weights

    # Encoder-level patch
    def _encoder_forward(self, inputs_embeds, attention_mask=None,
                         causal_attention_mask=None,
                         output_attentions=False,
                         output_hidden_states=False,
                         return_dict=True):
        all_hidden, all_attn = [], []
        hidden_states = inputs_embeds
        for layer in self.layers:
            if output_hidden_states:
                all_hidden.append(hidden_states)
            hidden_states, attn = layer(
                hidden_states,
                attention_mask=attention_mask,
                output_attentions=output_attentions,
            )
            if output_attentions:
                all_attn.append(attn)
        if output_hidden_states:
            all_hidden.append(hidden_states)

        if return_dict:
            return BaseModelOutput(
                last_hidden_state=hidden_states,
                hidden_states=tuple(all_hidden) if output_hidden_states else None,
                attentions=tuple(all_attn) if output_attentions else None,
            )
        return (hidden_states,
                tuple(all_hidden) if output_hidden_states else None,
                tuple(all_attn)   if output_attentions   else None)

    # Vision-transformer-level patch
    def _vit_forward(self, pixel_values, output_attentions=False,
                     output_hidden_states=False, return_dict=True):
        bsz    = pixel_values.shape[0]
        pe     = self.embeddings(pixel_values)
        enc_out = self.encoder(
            pe,
            output_attentions=output_attentions,
            output_hidden_states=output_hidden_states,
            return_dict=True,
        )
        seq    = enc_out.last_hidden_state
        pooled = self.post_layernorm(seq[:, 0, :])
        if return_dict:
            return BaseModelOutputWithPooling(
                last_hidden_state=seq,
                pooler_output=pooled,
                hidden_states=enc_out.hidden_states,
                attentions=enc_out.attentions,
            )
        return seq, pooled, enc_out.hidden_states, enc_out.attentions

    import types
    for layer in model.vision_model.encoder.layers:
        layer.forward = types.MethodType(_encoder_layer_forward, layer)
    model.vision_model.encoder.forward = types.MethodType(
        _encoder_forward, model.vision_model.encoder)
    model.vision_model.forward = types.MethodType(
        _vit_forward, model.vision_model)

    return model


