def loo_shapley(
    img: Image.Image,
    caption: str,
    patch_px: int = 32,
) -> np.ndarray:
    """
    Leave-one-out Shapley attribution over patch_px×patch_px patches.
    Returns (G×G) float32 map of CLIP-score drops.
    """
    size    = cfg.IMG_SIZE
    G       = size // patch_px
    img_np  = np.array(img.resize((size, size))).astype(np.float32)
    base_cs = clipscore(img, caption)
    grid    = np.zeros((G, G), dtype=np.float32)

    for i in range(G):
        for j in range(G):
            masked = img_np.copy()
            masked[i*patch_px:(i+1)*patch_px,
                   j*patch_px:(j+1)*patch_px] = 128.0   # grey-patch mask
            cs = clipscore(Image.fromarray(masked.astype(np.uint8)), caption)
            grid[i, j] = base_cs - cs

    grid = np.maximum(grid, 0)
    s    = grid.sum()
    return grid / (s + 1e-8) if s > 0 else grid


def shapley_flow(
    contrib_grid: np.ndarray,
    alpha: float = 0.85,
    steps: int = 20,
) -> np.ndarray:
    """
    Personalized PageRank over a 4-connected patch grid seeded by contrib_grid.
    Returns (G×G) float32 map normalized to sum=1.
    """
    gH, gW = contrib_grid.shape
    n      = gH * gW
    p0     = contrib_grid.flatten().astype(np.float64)
    p0     = p0 / (p0.sum() + 1e-12)

    def neighbors(idx):
        r, c = divmod(idx, gW)
        return [r2 * gW + c2
                for r2, c2 in [(r+1, c), (r-1, c), (r, c+1), (r, c-1)]
                if 0 <= r2 < gH and 0 <= c2 < gW]

    p = p0.copy()
    for _ in range(steps):
        p_new = (1 - alpha) * p0
        for i in range(n):
            nb = neighbors(i)
            if nb:
                share = alpha * p[i] / len(nb)
                for j in nb:
                    p_new[j] += share
        p = p_new

    p = p / (p.sum() + 1e-12)
    return p.reshape(gH, gW).astype(np.float32)


