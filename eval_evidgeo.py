def edge_corr(imgA: Image.Image, imgB: Image.Image) -> float:
    A  = np.array(imgA.convert("L")).astype(np.float32) / 255.0
    B  = np.array(imgB.convert("L")).astype(np.float32) / 255.0
    EA = filters.sobel(A).flatten()
    EB = filters.sobel(B).flatten()
    if np.std(EA) < 1e-6 or np.std(EB) < 1e-6:
        return 0.0
    return float(np.corrcoef(EA, EB)[0, 1])


def lpips_dist(imgA: Image.Image, imgB: Image.Image) -> float:
    tA = img_tf(imgA).unsqueeze(0).to(cfg.DEVICE) * 2 - 1
    tB = img_tf(imgB).unsqueeze(0).to(cfg.DEVICE) * 2 - 1
    with torch.no_grad():
        return float(lpips_model(tA, tB).item())


def topk_set(m2d: np.ndarray, k: int) -> set:
    return set(np.argsort(m2d.flatten())[-k:].tolist())


def jaccard(a: set, b: set) -> float:
    return len(a & b) / (len(a | b) + 1e-12)


def avg_pairwise_jaccard(sets: list) -> float:
    js = [jaccard(sets[i], sets[j])
          for i in range(len(sets)) for j in range(i + 1, len(sets))]
    return float(np.mean(js)) if js else float("nan")


